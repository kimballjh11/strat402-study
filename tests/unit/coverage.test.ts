/**
 * Coverage gate: every learning objective is taught (module screen), practiced (≥3 MCQs) and,
 * if quantitative, has ≥1 problem generator. Also writes content/coverage-report.md.
 */
import { writeFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { allLos, cqLos, generators, mcqs, sessionById } from '../../src/content'
import type { SessionId } from '../../src/content/types'

/** LOs that involve calculation (need a generator). */
const QUANT = new Set([
  'S03-LO2', 'S04-LO3', 'S05-LO1', 'S05-LO2', 'S06-LO2', 'S06-LO3', 'S07-LO2', 'S07-LO3', 'S07-LO4',
  'S08-LO2', 'S09-LO1', 'S09-LO3', 'S10-LO1', 'S10-LO4', 'S11-LO3', 'S12-LO3',
])

describe('LO coverage', () => {
  const rows = allLos.map((lo) => {
    const m = mcqs.filter((q) => q.los.includes(lo.id))
    const g = generators.filter((x) => x.los.includes(lo.id))
    const cq = Object.entries(cqLos).filter(([, l]) => l.includes(lo.id)).length
    const mod = sessionById[lo.session as SessionId]
    const srcs = [...new Set(m.map((q) => q.src.split(';')[0].replace(/^Variant of /, '').trim()))].slice(0, 4)
    const general = m.filter((q) => /General econ|\[\[GEN\]\]/.test(q.src + q.stem)).length
    return { lo, m: m.length, quiz: m.filter((q) => q.origin === 'cq' || q.origin === 'cq-variant').length, g: g.length, cq, mod, srcs, general }
  })

  it('writes content/coverage-report.md', () => {
    const lines = [
      '# Coverage report',
      '',
      `Generated by \`tests/unit/coverage.test.ts\` (runs with \`npm test\`). ${allLos.length} learning objectives · ${mcqs.length} MCQs · ${generators.length} problem generators · 40 verbatim Comprehension Quiz questions.`,
      '',
      'Gate: every LO has a lesson module, ≥3 MCQs, and (if quantitative) ≥1 generator. “Gen econ” counts MCQs labeled General econ (not from course materials).',
      '',
      '| LO | Objective | Lesson | MCQs (quiz-based) | Generators | CQ items | Gen econ | Main sources |',
      '| --- | --- | --- | --- | --- | --- | --- | --- |',
      ...rows.map(
        (r) =>
          `| ${r.lo.id} | ${r.lo.text.replace(/\|/g, '/').slice(0, 110)}${r.lo.text.length > 110 ? '…' : ''} | S${r.mod.num} ${r.mod.title}${r.mod.ready ? '' : ' (stub)'} | ${r.m} (${r.quiz}) | ${r.g}${QUANT.has(r.lo.id) ? '' : ' (n/a)'} | ${r.cq} | ${r.general} | ${r.srcs.join('; ')} |`,
      ),
      '',
      '## Notes',
      '',
      '- **S07-LO5** (four sources of differentiation): covered only through course evidence of differentiation (gross margin as willingness to pay, Whole Foods vs. Kroger). The professor’s four categories live in the LearnStrategy video, whose transcript is not in the inputs. See gap-report.md.',
      '- **S11** is built entirely from standard managerial economics (labeled) until the Session 11 slides are added.',
      '- **S01-LO3** is a derived LO (course policies tested in CQ1); it is not stated as an LO by the professor.',
      '',
    ]
    writeFileSync('content/coverage-report.md', lines.join('\n'))
    expect(rows.length).toBe(allLos.length)
  })

  it.each(rows.map((r) => [r.lo.id, r] as const))('%s is covered', (_id, r) => {
    expect(r.mod.ready, `${r.lo.id} module not built`).toBe(true)
    expect(r.m, `${r.lo.id} needs ≥3 MCQs`).toBeGreaterThanOrEqual(3)
    if (QUANT.has(r.lo.id)) expect(r.g, `${r.lo.id} needs a generator`).toBeGreaterThanOrEqual(1)
  })
})
